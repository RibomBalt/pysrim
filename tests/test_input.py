"""TRIM.IN / SR.IN 生成测试（不执行 TRIM.exe）。

输入文件格式是 pysrim 与 SRIM 之间唯一的契约，字段顺序错位会导致 TRIM 静默
算出错误结果，因此这里逐块校验。
"""

from __future__ import annotations

import pytest

from srim.core.ion import Ion
from srim.core.layer import Layer
from srim.input import SRInput, TRIMInput
from srim.srim import SR, SRIM


@pytest.fixture()
def trim_input(silicon_target, hydrogen_ion):
    from srim.srim import SRIM

    srim = SRIM(silicon_target, hydrogen_ion, number_ions=42, calculation=2, ranges=1)
    return TRIMInput(srim)


@pytest.fixture()
def trim_in_text(trim_input, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    trim_input.write()
    return (tmp_path / "TRIM.IN").read_bytes()


def test_trim_in_uses_crlf(trim_in_text):
    """SRIM 是 Windows 程序，输入文件必须是 CRLF。"""
    assert b"\r\n" in trim_in_text
    assert b"\n" not in trim_in_text.replace(b"\r\n", b"")


def test_trim_in_title_line(trim_in_text):
    lines = trim_in_text.decode("utf-8").split("\r\n")
    assert lines[0] == "This file controls TRIM Calculations generated by srim-python"


def test_trim_in_ion_block(trim_in_text):
    lines = trim_in_text.decode("utf-8").split("\r\n")
    assert lines[2].startswith("1 1.0079")  # Z=1, 质量 1.0079 amu
    fields = lines[2].split()
    assert fields[0] == "1"  # Z
    assert float(fields[2]) == pytest.approx(1000.0)  # eV -> keV
    assert fields[4] == "42"  # 离子数
    assert float(fields[1]) == pytest.approx(1.00794, rel=1e-4)


def test_trim_in_cascade_block(trim_in_text):
    lines = trim_in_text.decode("utf-8").split("\r\n")
    assert lines[4].split()[0] == "2"  # calculation 透传


def test_trim_in_target_block(trim_in_text):
    lines = trim_in_text.decode("utf-8").split("\r\n")
    assert lines[7] == "Target material : Number of Elements, Number of Layers"
    assert lines[8] == '"srim-python run" 1 1'  # 1 个元素、1 层


def test_trim_in_element_and_layer_block(trim_in_text):
    lines = trim_in_text.decode("utf-8").split("\r\n")
    element_line = next(line for line in lines if line.startswith("Atom 1 = Si"))
    assert element_line.split()[:4] == ["Atom", "1", "=", "Si"]
    assert float(element_line.split()[-1]) == pytest.approx(28.0855, rel=1e-4)

    layer_line = next(line for line in lines if line.startswith('1 "'))
    assert int(layer_line.split()[0]) == 1
    assert float(layer_line.split()[-3]) == pytest.approx(100_000.0)  # 厚度 Ang
    assert float(layer_line.split()[-2]) == pytest.approx(2.32)  # 密度


def test_trim_in_written_to_cwd_only(trim_in_text, tmp_path):
    assert (tmp_path / "TRIM.IN").is_file()


def test_diskfile_flags(trim_in_text):
    """ranges=1 时第 4 组第一个字段为 1（要求 RANGE.txt）。"""
    lines = trim_in_text.decode("utf-8").split("\r\n")
    assert lines[6].split()[0] == "1"


def test_sr_in_generation(tmp_path, monkeypatch):
    layer = Layer({"Si": 1.0}, density=2.32, width=100_000.0)
    sr = SR(layer, Ion("H", energy=1.0e6), energy_min=1.0e3)
    monkeypatch.chdir(tmp_path)
    SRInput(sr).write()

    text = (tmp_path / "SR.IN").read_text(encoding="utf-8")
    assert "---Ion(Z), Ion Mass(u)" in text
    assert "SR_OUTPUT.txt" in text


def test_srim_copies_known_output_files(tmp_path, srim_dir):
    """copy_output_files 只搬白名单文件，且两边目录都必须存在。"""
    src = tmp_path / "src"
    dest = tmp_path / "dest"
    src.mkdir()
    dest.mkdir()
    (src / "RANGE.txt").write_text("dummy", encoding="utf-8")
    (src / "UNRELATED.txt").write_text("dummy", encoding="utf-8")

    SRIM.copy_output_files(str(src), str(dest))

    assert (dest / "RANGE.txt").is_file()
    assert not (dest / "UNRELATED.txt").exists()

    with pytest.raises(ValueError):
        SRIM.copy_output_files(str(tmp_path / "missing"), str(dest))


def test_srim_copies_auxiliary_outputs_from_srim_outputs_dir(tmp_path):
    """TRIM 把辅助输出写进 'SRIM Outputs' 子目录，包括拼写古怪的 COLLISON.txt。"""
    src = tmp_path / "src"
    dest = tmp_path / "dest"
    (src / "SRIM Outputs").mkdir(parents=True)
    dest.mkdir()
    for filename in ("SPUTTER.txt", "TRANSMIT.txt", "BACKSCAT.txt", "COLLISON.txt"):
        (src / "SRIM Outputs" / filename).write_text("dummy", encoding="utf-8")

    SRIM.copy_output_files(str(src), str(dest))

    for filename in ("SPUTTER.txt", "TRANSMIT.txt", "BACKSCAT.txt", "COLLISON.txt"):
        assert (dest / filename).is_file(), filename


def test_srim_can_skip_the_srim_outputs_dir(tmp_path):
    src = tmp_path / "src"
    dest = tmp_path / "dest"
    (src / "SRIM Outputs").mkdir(parents=True)
    dest.mkdir()
    (src / "SRIM Outputs" / "SPUTTER.txt").write_text("dummy", encoding="utf-8")

    SRIM.copy_output_files(str(src), str(dest), check_srim_output=False)

    assert not (dest / "SPUTTER.txt").exists()
